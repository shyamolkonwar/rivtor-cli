import type { Command } from "commander";
import { Option } from "commander";
import { existsSync } from "node:fs";
import { cp, mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { homedir } from "node:os";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import pc from "picocolors";
import { CliError, action, printJson } from "../context.js";

export const SKILL_NAME = "rivtor";
export const SKILL_TARGETS = ["claude", "codex", "cursor"] as const;
export type SkillTarget = (typeof SKILL_TARGETS)[number];

const LABELS: Record<SkillTarget, string> = {
  claude: "Claude Code",
  codex: "Codex",
  cursor: "Cursor",
};

/** The skill folder shipped in the npm package (`skills/rivtor`, next to `dist/`). */
export function bundledSkillDir(): string {
  return fileURLToPath(new URL(`../../skills/${SKILL_NAME}`, import.meta.url));
}

export interface InstallOptions {
  /** install into the project (cwd) instead of the user's home directory */
  project?: boolean;
  cwd?: string;
  home?: string;
  /** override the bundled skill folder (tests) */
  source?: string;
}

export interface Installed {
  target: SkillTarget;
  path: string;
}

/**
 * Where each agent discovers skills:
 * - Claude Code: ~/.claude/skills/<name>/ or <project>/.claude/skills/<name>/
 * - Codex: ~/.agents/skills/<name>/ or <project>/.agents/skills/<name>/ (developers.openai.com/codex/skills)
 * - Cursor: project rules only, <project>/.cursor/rules/<name>.mdc (references next to it)
 */
export function skillDestination(
  target: SkillTarget,
  opts: InstallOptions = {},
): string {
  const base =
    opts.project || target === "cursor"
      ? resolve(opts.cwd ?? process.cwd())
      : (opts.home ?? (process.env.HOME || homedir()));
  if (target === "claude") return join(base, ".claude", "skills", SKILL_NAME);
  if (target === "codex") return join(base, ".agents", "skills", SKILL_NAME);
  return join(base, ".cursor", "rules", `${SKILL_NAME}.mdc`);
}

/** Splits SKILL.md into its frontmatter fields (flat keys and `>-` folded blocks) and body. */
export function parseSkillMd(text: string): {
  fields: Record<string, string>;
  body: string;
} {
  const m = /^---\r?\n([\s\S]*?)\r?\n---\r?\n?([\s\S]*)$/.exec(text);
  if (!m) throw new CliError("SKILL.md has no YAML frontmatter");
  const fields: Record<string, string> = {};
  let key: string | null = null;
  let folded: string[] = [];
  const flush = () => {
    if (key) fields[key] = folded.join(" ").trim();
    key = null;
    folded = [];
  };
  for (const line of m[1]!.split(/\r?\n/)) {
    const kv = /^([A-Za-z][\w-]*):\s*(.*)$/.exec(line);
    if (kv) {
      flush();
      const value = kv[2]!.trim();
      if (/^[>|][-+]?$/.test(value)) key = kv[1]!;
      else fields[kv[1]!] = value.replace(/^(["'])(.*)\1$/, "$2");
    } else if (key && /^\s+\S/.test(line)) {
      folded.push(line.trim());
    }
  }
  flush();
  return { fields, body: m[2]! };
}

/** Cursor project rule generated from SKILL.md: "Apply Intelligently" (description, no globs). */
export function cursorRule(skillMd: string): string {
  const { fields, body } = parseSkillMd(skillMd);
  if (!fields.description)
    throw new CliError("SKILL.md frontmatter has no description");
  const rewritten = body
    .replace(/\]\(references\//g, `](${SKILL_NAME}/references/`)
    .trimStart();
  return [
    "---",
    `description: ${JSON.stringify(fields.description)}`,
    "alwaysApply: false",
    "---",
    "",
    `<!-- Generated by \`rivtor skills install --target cursor\` from the Rivtor skill. Reference files: .cursor/rules/${SKILL_NAME}/references/ -->`,
    "",
    rewritten,
  ].join("\n");
}

async function replaceDir(from: string, to: string): Promise<void> {
  await rm(to, { recursive: true, force: true });
  await mkdir(resolve(to, ".."), { recursive: true });
  await cp(from, to, { recursive: true });
}

export async function installSkill(
  target: SkillTarget,
  opts: InstallOptions = {},
): Promise<Installed> {
  const source = opts.source ?? bundledSkillDir();
  if (!existsSync(join(source, "SKILL.md")))
    throw new CliError(
      `Bundled skill not found at ${source}. Reinstall rivtor.`,
    );
  const dest = skillDestination(target, opts);
  if (target === "cursor") {
    const rule = cursorRule(await readFile(join(source, "SKILL.md"), "utf8"));
    await mkdir(resolve(dest, ".."), { recursive: true });
    await writeFile(dest, rule);
    const refs = join(source, "references");
    const refsDest = join(dest.replace(/\.mdc$/, ""), "references");
    if (existsSync(refs)) await replaceDir(refs, refsDest);
    return { target, path: dest };
  }
  await replaceDir(source, dest);
  return { target, path: dest };
}

export function registerSkills(program: Command): void {
  const skills = program
    .command("skills")
    .description("Install the Rivtor agent skill (Claude Code, Codex, Cursor)");

  skills
    .command("install")
    .description(
      "Copy the Rivtor skill to where your coding agent loads skills",
    )
    .addOption(
      new Option("-t, --target <target>", "agent to install for")
        .choices([...SKILL_TARGETS, "all"])
        .default("claude"),
    )
    .option(
      "--project",
      "install into the current project instead of your home directory (Cursor is always per project)",
    )
    .option("--json", "print JSON")
    .action(
      action(
        async (opts: {
          target: SkillTarget | "all";
          project?: boolean;
          json?: boolean;
        }) => {
          const targets =
            opts.target === "all" ? [...SKILL_TARGETS] : [opts.target];
          const installed: Installed[] = [];
          for (const t of targets)
            installed.push(await installSkill(t, { project: opts.project }));
          if (opts.json)
            return printJson({ skill: bundledSkillDir(), installed });
          for (const i of installed)
            process.stdout.write(
              `${pc.green("✓")} ${LABELS[i.target]}: ${i.path}\n`,
            );
          process.stdout.write(
            pc.dim("Start a new agent session to load the skill.\n"),
          );
        },
      ),
    );

  skills
    .command("path")
    .description("Print the folder of the bundled Rivtor skill")
    .action(
      action(async () => {
        const dir = bundledSkillDir();
        if (!existsSync(join(dir, "SKILL.md")))
          throw new CliError(
            `Bundled skill not found at ${dir}. Reinstall rivtor.`,
          );
        process.stdout.write(`${dir}\n`);
      }),
    );
}
